-- Oracle schema for IPL player performance dashboard (analytics-ready subset)
CREATE TABLE IPL_MATCHES (
  MATCH_ID NUMBER PRIMARY KEY,
  MATCH_DATE DATE,
  SEASON VARCHAR2(20), CITY VARCHAR2(100), VENUE VARCHAR2(250),
  TEAM1 VARCHAR2(120), TEAM2 VARCHAR2(120), TOSS_WINNER VARCHAR2(120),
  TOSS_DECISION VARCHAR2(30), WINNER VARCHAR2(120), PLAYER_OF_MATCH VARCHAR2(120),
  MATCH_TYPE VARCHAR2(30), OVERS NUMBER, BALLS_PER_OVER NUMBER
);

CREATE TABLE IPL_BALL_BY_BALL (
  MATCH_ID NUMBER, MATCH_DATE DATE, SEASON VARCHAR2(20), CITY VARCHAR2(100), VENUE VARCHAR2(250),
  TEAM1 VARCHAR2(120), TEAM2 VARCHAR2(120), BATTING_TEAM VARCHAR2(120), BOWLING_TEAM VARCHAR2(120),
  INNINGS NUMBER, OVER_NO NUMBER, BALL_IN_OVER NUMBER, LEGAL_BALL NUMBER, LEGAL_BALL_NUMBER NUMBER,
  BATTER VARCHAR2(120), BOWLER VARCHAR2(120), NON_STRIKER VARCHAR2(120),
  BATTER_RUNS NUMBER, EXTRA_RUNS NUMBER, TOTAL_RUNS NUMBER, WIDES NUMBER, NOBALLS NUMBER,
  BYES NUMBER, LEG_BYES NUMBER, PENALTY NUMBER, IS_BOUNDARY_4 NUMBER, IS_BOUNDARY_6 NUMBER,
  IS_DOT_BALL NUMBER, IS_WICKET NUMBER, WICKET_COUNT NUMBER, WICKET_PLAYER_OUT VARCHAR2(120),
  WICKET_KIND VARCHAR2(50), WICKET_FIELDERS VARCHAR2(4000),
  INNINGS_RUNS_SO_FAR NUMBER, INNINGS_WICKETS_SO_FAR NUMBER, BALLS_REMAINING NUMBER,
  CURRENT_RUN_RATE NUMBER, PHASE VARCHAR2(30), IS_POWERPLAY NUMBER, IS_MIDDLE_OVERS NUMBER,
  IS_DEATH_OVERS NUMBER, TOSS_WINNER VARCHAR2(120), TOSS_DECISION VARCHAR2(30),
  MATCH_WINNER VARCHAR2(120), BATTING_TEAM_WON NUMBER, TARGET NUMBER, RUNS_REQUIRED NUMBER,
  REQUIRED_RUN_RATE NUMBER, IS_CHASING NUMBER
);

CREATE INDEX IX_IPLB_MATCH_SEASON ON IPL_BALL_BY_BALL(SEASON, MATCH_ID);
CREATE INDEX IX_IPLB_BATTER ON IPL_BALL_BY_BALL(BATTER);
CREATE INDEX IX_IPLB_BOWLER ON IPL_BALL_BY_BALL(BOWLER);
