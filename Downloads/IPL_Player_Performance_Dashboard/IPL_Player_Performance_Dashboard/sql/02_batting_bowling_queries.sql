-- Batting season-level aggregates. Balls faced exclude wides; no-balls count as balls faced.
CREATE OR REPLACE VIEW VW_IPL_BATTER_STATS AS
WITH RUNS AS (
  SELECT SEASON, BATTER PLAYER, SUM(BATTER_RUNS) RUNS,
         COUNT(DISTINCT MATCH_ID) MATCHES,
         SUM(CASE WHEN NVL(WIDES,0)=0 THEN 1 ELSE 0 END) BALLS_FACED,
         SUM(IS_BOUNDARY_4) FOURS, SUM(IS_BOUNDARY_6) SIXES
  FROM IPL_BALL_BY_BALL GROUP BY SEASON, BATTER
), DISMISSALS AS (
  SELECT SEASON, WICKET_PLAYER_OUT PLAYER,
         COUNT(*) TOTAL_DISMISSALS
  FROM IPL_BALL_BY_BALL WHERE IS_WICKET=1 AND WICKET_PLAYER_OUT IS NOT NULL
    AND LOWER(WICKET_KIND) NOT IN ('retired hurt','obstructing the field')
  GROUP BY SEASON, WICKET_PLAYER_OUT
)
SELECT R.SEASON, R.PLAYER, R.RUNS, R.MATCHES, R.BALLS_FACED, R.FOURS, R.SIXES,
       NVL(D.TOTAL_DISMISSALS,0) DISMISSALS,
       CASE WHEN NVL(D.TOTAL_DISMISSALS,0)=0 THEN NULL ELSE ROUND(R.RUNS/D.TOTAL_DISMISSALS,2) END BATTING_AVERAGE,
       CASE WHEN R.BALLS_FACED=0 THEN NULL ELSE ROUND(100*R.RUNS/R.BALLS_FACED,2) END STRIKE_RATE
FROM RUNS R LEFT JOIN DISMISSALS D ON D.SEASON=R.SEASON AND D.PLAYER=R.PLAYER;

-- Bowling aggregates. Conceded runs exclude byes, leg-byes and penalty; wides/no-balls count.
CREATE OR REPLACE VIEW VW_IPL_BOWLER_STATS AS
SELECT SEASON, BOWLER PLAYER, COUNT(DISTINCT MATCH_ID) MATCHES,
       SUM(CASE WHEN NVL(WIDES,0)=0 AND NVL(NOBALLS,0)=0 THEN 1 ELSE 0 END) LEGAL_BALLS,
       SUM(TOTAL_RUNS-NVL(BYES,0)-NVL(LEG_BYES,0)-NVL(PENALTY,0)) RUNS_CONCEDED,
       SUM(CASE WHEN IS_WICKET=1 AND LOWER(WICKET_KIND) NOT IN ('run out','retired hurt','obstructing the field') THEN 1 ELSE 0 END) WICKETS,
       CASE WHEN SUM(CASE WHEN NVL(WIDES,0)=0 AND NVL(NOBALLS,0)=0 THEN 1 ELSE 0 END)=0 THEN NULL
            ELSE ROUND(6*SUM(TOTAL_RUNS-NVL(BYES,0)-NVL(LEG_BYES,0)-NVL(PENALTY,0))/SUM(CASE WHEN NVL(WIDES,0)=0 AND NVL(NOBALLS,0)=0 THEN 1 ELSE 0 END),2) END ECONOMY,
       CASE WHEN SUM(CASE WHEN IS_WICKET=1 AND LOWER(WICKET_KIND) NOT IN ('run out','retired hurt','obstructing the field') THEN 1 ELSE 0 END)=0 THEN NULL
            ELSE ROUND(SUM(TOTAL_RUNS-NVL(BYES,0)-NVL(LEG_BYES,0)-NVL(PENALTY,0))/SUM(CASE WHEN IS_WICKET=1 AND LOWER(WICKET_KIND) NOT IN ('run out','retired hurt','obstructing the field') THEN 1 ELSE 0 END),2) END BOWLING_AVERAGE,
       CASE WHEN SUM(CASE WHEN IS_WICKET=1 AND LOWER(WICKET_KIND) NOT IN ('run out','retired hurt','obstructing the field') THEN 1 ELSE 0 END)=0 THEN NULL
            ELSE ROUND(SUM(CASE WHEN NVL(WIDES,0)=0 AND NVL(NOBALLS,0)=0 THEN 1 ELSE 0 END)/SUM(CASE WHEN IS_WICKET=1 AND LOWER(WICKET_KIND) NOT IN ('run out','retired hurt','obstructing the field') THEN 1 ELSE 0 END),2) END BOWLING_STRIKE_RATE
FROM IPL_BALL_BY_BALL GROUP BY SEASON, BOWLER;

-- Top 10 batter by season (dense rank handles ties without skipping rank numbers).
SELECT * FROM (
  SELECT SEASON, PLAYER, RUNS,
         DENSE_RANK() OVER (PARTITION BY SEASON ORDER BY RUNS DESC) RUNS_RANK
  FROM VW_IPL_BATTER_STATS
) WHERE RUNS_RANK <= 10 ORDER BY SEASON, RUNS_RANK, PLAYER;

-- Top 10 bowler by wickets per season.
SELECT * FROM (
  SELECT SEASON, PLAYER, WICKETS,
         DENSE_RANK() OVER (PARTITION BY SEASON ORDER BY WICKETS DESC) WICKET_RANK
  FROM VW_IPL_BOWLER_STATS
) WHERE WICKET_RANK <= 10 ORDER BY SEASON, WICKET_RANK, PLAYER;

-- Player comparison: choose a season and a shortlist of names in the WHERE clause.
-- Example: WHERE SEASON = '2024' AND PLAYER IN ('Player A','Player B')
SELECT SEASON, PLAYER, RUNS, MATCHES, BALLS_FACED, BATTING_AVERAGE, STRIKE_RATE, FOURS, SIXES
FROM VW_IPL_BATTER_STATS ORDER BY RUNS DESC;
